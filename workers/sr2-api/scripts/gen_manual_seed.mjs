// Builds migrations/0005_manual_seed.sql and the book's image files from the approved interactive Roadie Manual,
// so the wording and artwork are the approved ones, not retyped. The source file is only read.
//   node scripts/gen_manual_seed.mjs "<...>/SR_Roadie_Manual_Interactive_Book.html" "<site public dir>"
// Everything imported is status needs_review: the source says "Not approved policy", so nothing is published here.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const [src, publicDir] = process.argv.slice(2);
const raw = readFileSync(src, "utf8");
const pages = JSON.parse(raw.match(/const allPages=(\[[\s\S]*?\]);\s*\n?let position/)[1]);
const NOW = Date.UTC(2026, 9, 31);
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";

// book page index -> [chapter number]
const CHAPTER_OF = { 2: 1, 3: 2, 4: 2, 5: 3, 6: 3, 7: 4, 8: 4, 9: 5, 10: 5, 11: 5, 12: 6, 13: 6 };
const lines = ["-- GENERATED by scripts/gen_manual_seed.mjs from the approved Roadie Manual. Status needs_review: Moose publishes.", ""];
const ordInChapter = {};
for (const [i, chapter] of Object.entries(CHAPTER_OF)) {
  const page = pages[+i];
  const title = page.match(/<h2>\s*(.*?)\s*<\/h2>/)[1].replace(/&amp;/g, "&").trim();
  const body = page.match(/data-edit="chapter-\d+"[^>]*>([\s\S]*?)<\/div><p class="editable-hint">/)[1].replace(/ class=""/g, "").trim();
  const ord = (ordInChapter[chapter] = (ordInChapter[chapter] ?? 0) + 1);
  const slug = `ch${chapter}-${ord}`;
  lines.push(`INSERT INTO policies(slug, chapter, ord, title, status, draft_html, updated_at) VALUES (${q(slug)}, ${chapter}, ${ord}, ${q(title)}, 'needs_review', ${q(body)}, ${NOW});`);
  lines.push(`INSERT INTO policy_versions(policy_id, title, html, kind, at) SELECT id, title, draft_html, 'imported', ${NOW} FROM policies WHERE slug = ${q(slug)};`);
}

// Every open item on the manual's "Decisions & Procedures" pages, plus the extra questions in the 2.0 brief.
const manualQuestions = [...raw.matchAll(/<div class=\\"checkitem\\">(.*?)<\\\/div>/g)].map((m) => JSON.parse(`"${m[1]}"`));
const CHAPTER_HINT = [[/callout|absence|notice|swap|schedule|scheduler|coverage|replacement/i, 3], [/arrival|music|broadcast|host handle|management roles|independently|moose approval|promotion/i, 4],
  [/conflict|unresolved|warn|remove|ban|incident|technical|equipment|reset/i, 5], [/event|ideas|promo|recognition|feedback/i, 6]];
const hint = (t) => CHAPTER_HINT.find(([re]) => re.test(t))?.[1] ?? null;
const briefQuestions = ["Official callout channel", "Required absence notice", "DJ scheduling responsibility", "Host scheduling responsibility", "Emergency coverage procedure",
  "DJ Trial approval policy", "Host Trial approval policy", "DJ and Host of the Month rules", "Staff recognition rules", "Management responsibilities"];
lines.push("");
for (const t of manualQuestions) lines.push(`INSERT OR IGNORE INTO policy_questions(topic, chapter, source, updated_at) VALUES (${q(t)}, ${hint(t) ?? "NULL"}, 'manual review pages', ${NOW});`);
for (const t of briefQuestions) lines.push(`INSERT OR IGNORE INTO policy_questions(topic, chapter, source, updated_at) VALUES (${q(t)}, ${hint(t) ?? "NULL"}, 'SR 2.0 brief', ${NOW});`);

const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, "../migrations/0005_manual_seed.sql"), lines.join("\n") + "\n");

// the approved cover + crest, exactly as embedded in the book
if (publicDir) {
  const out = join(publicDir, "images/backstage/roadie");
  mkdirSync(out, { recursive: true });
  const cover = raw.match(/const coverURI="data:image\/jpeg;base64,([A-Za-z0-9+/=]+)"/)[1];
  writeFileSync(join(out, "roadie-cover.jpg"), Buffer.from(cover, "base64"));
  const crests = [...pages.join("").matchAll(/class="crest( smallcrest)?" src="data:image\/png;base64,([A-Za-z0-9+/=]+)"/g)];
  writeFileSync(join(out, "roadie-crest.png"), Buffer.from(crests[0][2], "base64"));
}
console.log(`policies ${Object.keys(CHAPTER_OF).length}, manual questions ${manualQuestions.length}, brief questions ${briefQuestions.length}`);
